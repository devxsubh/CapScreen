import type { StartupDocument } from "@/lib/startupsApi";
import { escapeHtml } from "@/lib/escapeHtml";

/** Rough markdown → HTML for Word-compatible .doc export. */
function markdownToSimpleHtml(md: string): string {
  const lines = md.split("\n");
  const parts: string[] = [];
  let inTable = false;

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      if (inTable) {
        parts.push("</table>");
        inTable = false;
      }
      parts.push("<br/>");
      continue;
    }
    if (trimmed.startsWith("# ")) {
      parts.push(`<h1>${escapeHtml(trimmed.slice(2))}</h1>`);
      continue;
    }
    if (trimmed.startsWith("## ")) {
      parts.push(`<h2>${escapeHtml(trimmed.slice(3))}</h2>`);
      continue;
    }
    if (trimmed.startsWith("### ")) {
      parts.push(`<h3>${escapeHtml(trimmed.slice(4))}</h3>`);
      continue;
    }
    if (trimmed.startsWith("|") && trimmed.endsWith("|")) {
      const cells = trimmed
        .slice(1, -1)
        .split("|")
        .map((c) => c.trim());
      if (cells.every((c) => /^-+$/.test(c))) continue;
      if (!inTable) {
        parts.push(
          '<table border="1" cellpadding="6" cellspacing="0" style="border-collapse:collapse;width:100%;">',
        );
        inTable = true;
      }
      parts.push(
        `<tr>${cells.map((c) => `<td>${escapeHtml(c)}</td>`).join("")}</tr>`,
      );
      continue;
    }
    if (inTable) {
      parts.push("</table>");
      inTable = false;
    }
    if (trimmed.startsWith("- ")) {
      parts.push(`<li>${escapeHtml(trimmed.slice(2))}</li>`);
      continue;
    }
    parts.push(`<p>${escapeHtml(trimmed)}</p>`);
  }
  if (inTable) parts.push("</table>");
  return parts.join("\n");
}

export function downloadIcMemoAsDoc(doc: StartupDocument): void {
  const body = markdownToSimpleHtml(doc.content);
  const html = `<!DOCTYPE html>
<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:w="urn:schemas-microsoft-com:office:word">
<head><meta charset="utf-8"><title>${escapeHtml(doc.title)}</title></head>
<body style="font-family: Calibri, Arial, sans-serif; font-size: 11pt; line-height: 1.4;">
${body}
</body></html>`;

  const blob = new Blob([html], { type: "application/msword" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${doc.title.replace(/[^\w\s-]/g, "").replace(/\s+/g, "-")}.doc`;
  a.click();
  URL.revokeObjectURL(url);
}

/** Desktop: render the memo with print styling and save it as a PDF. */
export async function downloadIcMemoAsPdf(doc: StartupDocument): Promise<string | null> {
  const bridge = typeof window !== "undefined" ? window.capscreenDesktop : undefined;
  if (!bridge) throw new Error("PDF export is available in the desktop app");
  const html = `<!DOCTYPE html><html><head><meta charset="utf-8"><title>${escapeHtml(doc.title)}</title>
<style>
  @page { margin: 22mm 18mm; }
  body { font-family: -apple-system, "Segoe UI", Calibri, Arial, sans-serif; font-size: 10.5pt; line-height: 1.5; color: #111; }
  h1 { font-family: Georgia, serif; font-size: 20pt; font-weight: 500; margin: 0 0 8pt; }
  h2 { font-family: Georgia, serif; font-size: 14pt; font-weight: 500; margin: 16pt 0 6pt; border-bottom: 1px solid #ddd; padding-bottom: 3pt; }
  h3 { font-size: 11pt; margin: 12pt 0 4pt; }
  table { border-collapse: collapse; width: 100%; margin: 6pt 0; font-size: 9.5pt; }
  td { border: 1px solid #ccc; padding: 4pt 6pt; vertical-align: top; }
  tr:first-child td { background: #f3f4f6; font-weight: 600; }
  li { margin-left: 14pt; }
  .footer { margin-top: 24pt; padding-top: 6pt; border-top: 1px solid #ddd; font-size: 8pt; color: #666; }
</style></head><body>
${markdownToSimpleHtml(doc.content)}
<div class="footer">Generated by CapScreen on ${escapeHtml(new Date().toLocaleString())}. Screening decision support only — not a legal determination. Confidential.</div>
</body></html>`;
  return bridge.printToPdf({ html, defaultName: `${doc.title.replace(/[^\w\s-]/g, "").replace(/\s+/g, "-")}.pdf` });
}
